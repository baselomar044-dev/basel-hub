export const qsFormulas = {
  // Area calculations
  builtUpArea: (length: number, width: number, floors: number) => length * width * floors,
  carpetArea: (builtUp: number) => builtUp * 0.75, // Typically 75% of built-up
  superBuiltUp: (builtUp: number) => builtUp * 1.25, // Including common areas
  
  // Concrete calculations
  concreteVolume: (length: number, width: number, thickness: number) => length * width * thickness,
  steelWeight: (concreteVolume: number, kgPerM3: number = 100) => concreteVolume * kgPerM3,
  
  // Blockwork
  blocksRequired: (wallArea: number, blockSize: number = 0.08) => Math.ceil(wallArea / blockSize),
  mortarVolume: (wallArea: number) => wallArea * 0.02, // 20mm thick mortar
  
  // Paint
  paintArea: (wallArea: number, coats: number = 2) => wallArea * coats,
  paintLiters: (area: number, coveragePerLiter: number = 10) => area / coveragePerLiter,
  
  // Cost estimates
  costPerSqft: (totalCost: number, area: number) => totalCost / area,
  contingency: (cost: number, percentage: number = 10) => cost * (percentage / 100),
  markup: (cost: number, percentage: number = 15) => cost * (1 + percentage / 100),
}

